    def generate_vaccine_script(self, report_data: Dict[str, Any]) -> str:
        """
        Extracts Mutexes and Registry Paths, then builds the script template.
        Returns the raw python code string.
        """
        mutexes = self._extract_mutexes(report_data)
        reg_keys = self._extract_registry_keys(report_data)
        
        # Deduplicate
        mutexes = list(set(mutexes))
        reg_keys = list(set(reg_keys))
        
        return self._build_template(mutexes, reg_keys)

    def _extract_mutexes(self, report_data: Dict[str, Any]) -> List[str]:
        mutexes = []
        
        # 1. Static Extraction
        artifacts = report_data.get("intelligence", {}).get("artifacts", {})
        static_mutexes = artifacts.get("mutex", [])
        mutexes.extend(static_mutexes)
        
        # 2. Dynamic Execution Timeline
        timeline = report_data.get("dynamic", {}).get("strace", {}).get("timeline", [])
        for event in timeline:
            action = event.get("action", "")
            if "Mutex: " in action:
                m = action.split("Mutex: ")[-1].strip()
                mutexes.append(m)
                
        return mutexes

    def _extract_registry_keys(self, report_data: Dict[str, Any]) -> List[str]:
        reg_keys = []
        
        # 1. Static Extraction
        artifacts = report_data.get("intelligence", {}).get("artifacts", {})
        static_regs = artifacts.get("registry_key", [])
        reg_keys.extend(static_regs)
        
        # 2. Dynamic Execution Timeline
        timeline = report_data.get("dynamic", {}).get("strace", {}).get("timeline", [])
        for event in timeline:
            action = event.get("action", "")
            if "Registry: " in action:
                r = action.split("Registry: ")[-1].strip()
                reg_keys.append(r)
                
        return reg_keys

